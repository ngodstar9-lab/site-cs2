-- Quran reading website setup for Supabase.
-- Run once in Supabase SQL Editor. Uses the existing site administrator account.
create table if not exists public.quran_announcements (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 160),
  body text not null check (char_length(body) between 1 and 4000),
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.quran_site_settings (
  key text primary key,
  value text not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.quran_feedback (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 80),
  message text not null check (char_length(message) between 5 and 1200),
  status text not null default 'new' check (status in ('new','read')),
  created_at timestamptz not null default now()
);

alter table public.quran_announcements enable row level security;
alter table public.quran_site_settings enable row level security;
alter table public.quran_feedback enable row level security;

drop policy if exists "Public can read published Quran announcements" on public.quran_announcements;
drop policy if exists "Manager manages Quran announcements" on public.quran_announcements;
drop policy if exists "Public can read Quran site settings" on public.quran_site_settings;
drop policy if exists "Manager manages Quran site settings" on public.quran_site_settings;
drop policy if exists "Visitors can send Quran feedback" on public.quran_feedback;
drop policy if exists "Manager manages Quran feedback" on public.quran_feedback;

create policy "Public can read published Quran announcements"
on public.quran_announcements for select to anon, authenticated
using (is_published = true or auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid);

create policy "Manager manages Quran announcements"
on public.quran_announcements for all to authenticated
using (auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid)
with check (auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid);

create policy "Public can read Quran site settings"
on public.quran_site_settings for select to anon, authenticated using (true);

create policy "Manager manages Quran site settings"
on public.quran_site_settings for all to authenticated
using (auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid)
with check (auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid);

create policy "Visitors can send Quran feedback"
on public.quran_feedback for insert to anon, authenticated
with check (
  status = 'new'
  and char_length(name) between 1 and 80
  and char_length(message) between 5 and 1200
);

create policy "Manager manages Quran feedback"
on public.quran_feedback for all to authenticated
using (auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid)
with check (auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid);

grant select on public.quran_announcements, public.quran_site_settings to anon, authenticated;
grant insert, update, delete on public.quran_announcements, public.quran_site_settings to authenticated;
grant usage, select on sequence public.quran_announcements_id_seq to authenticated;
grant insert (name, message) on public.quran_feedback to anon, authenticated;
grant select, update, delete on public.quran_feedback to authenticated;
grant usage, select on sequence public.quran_feedback_id_seq to authenticated;

-- Optional defaults used by the public reader.
insert into public.quran_site_settings (key, value)
values
  ('translation_edition', 'fa.makarem'),
  ('reciter_edition', 'ar.alafasy'),
  ('daily_ayah_ref', '2:255'),
  ('daily_ayah_note', 'آیه‌ای برای تأمل و یادآوری')
on conflict (key) do nothing;
