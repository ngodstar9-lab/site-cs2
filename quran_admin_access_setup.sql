-- Owner-reviewed Quran website admin access requests and role management.
-- Run once AFTER quran_setup.sql.
-- This script contains no dollar-quoted function body and never grants admin automatically.

create table if not exists public.quran_admin_requests (
  id bigint generated by default as identity primary key,
  display_name text not null check (char_length(display_name) between 2 and 80),
  contact text not null check (char_length(contact) between 5 and 160),
  reason text not null check (char_length(reason) between 20 and 1500),
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  owner_note text,
  created_at timestamptz not null default now(),
  decided_at timestamptz
);

create table if not exists public.quran_admin_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'admin' check (role in ('owner','admin')),
  label text not null default 'مدیر سایت' check (char_length(label) between 2 and 100),
  granted_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.quran_admin_requests enable row level security;
alter table public.quran_admin_roles enable row level security;

-- Seed the existing owner account. This does not create any additional admin.
insert into public.quran_admin_roles (user_id, role, label)
values ('8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid, 'owner', 'اونر سایت')
on conflict (user_id) do update set role = 'owner', label = 'اونر سایت';

-- Public visitors can submit requests, but cannot read or decide them.
drop policy if exists "Visitors can request Quran admin access" on public.quran_admin_requests;
drop policy if exists "Only owner can review Quran admin requests" on public.quran_admin_requests;
create policy "Visitors can request Quran admin access"
on public.quran_admin_requests
for insert to anon, authenticated
with check (
  status = 'pending'
  and owner_note is null
  and decided_at is null
  and char_length(display_name) between 2 and 80
  and char_length(contact) between 5 and 160
  and char_length(reason) between 20 and 1500
);

create policy "Only owner can review Quran admin requests"
on public.quran_admin_requests
for all to authenticated
using (auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid)
with check (auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid);

-- Users can read their own role; only the fixed owner can manage all roles.
drop policy if exists "Users can view their own Quran admin role" on public.quran_admin_roles;
drop policy if exists "Only owner can manage Quran admin roles" on public.quran_admin_roles;
create policy "Users can view their own Quran admin role"
on public.quran_admin_roles
for select to authenticated
using (
  auth.uid() = user_id
  or auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid
);
create policy "Only owner can manage Quran admin roles"
on public.quran_admin_roles
for all to authenticated
using (auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid)
with check (auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid);

-- Approved admins can manage announcements and feedback.
-- No helper function or dollar-quoted SQL body is needed.
drop policy if exists "Manager manages Quran announcements" on public.quran_announcements;
drop policy if exists "Quran admins manage announcements" on public.quran_announcements;
create policy "Quran admins manage announcements"
on public.quran_announcements
for all to authenticated
using (
  auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid
  or exists (
    select 1 from public.quran_admin_roles r
    where r.user_id = auth.uid() and r.role in ('owner','admin')
  )
)
with check (
  auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid
  or exists (
    select 1 from public.quran_admin_roles r
    where r.user_id = auth.uid() and r.role in ('owner','admin')
  )
);

-- Only the owner can change site-wide settings such as admin-access conditions.
drop policy if exists "Manager manages Quran site settings" on public.quran_site_settings;
drop policy if exists "Only owner manages Quran site settings" on public.quran_site_settings;
create policy "Only owner manages Quran site settings"
on public.quran_site_settings
for all to authenticated
using (auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid)
with check (auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid);

drop policy if exists "Manager manages Quran feedback" on public.quran_feedback;
drop policy if exists "Quran admins manage feedback" on public.quran_feedback;
create policy "Quran admins manage feedback"
on public.quran_feedback
for all to authenticated
using (
  auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid
  or exists (
    select 1 from public.quran_admin_roles r
    where r.user_id = auth.uid() and r.role in ('owner','admin')
  )
)
with check (
  auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid
  or exists (
    select 1 from public.quran_admin_roles r
    where r.user_id = auth.uid() and r.role in ('owner','admin')
  )
);

grant insert (display_name, contact, reason) on public.quran_admin_requests to anon, authenticated;
grant select, update, delete on public.quran_admin_requests to authenticated;
grant usage, select on sequence public.quran_admin_requests_id_seq to anon, authenticated;

grant select on public.quran_admin_roles to authenticated;
grant insert, update, delete on public.quran_admin_roles to authenticated;

