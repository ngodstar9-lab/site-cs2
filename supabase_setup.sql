create table if not exists public.people (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) <= 80),
  game_id text,
  role text default 'عضو کامیونیتی',
  created_at timestamptz not null default now()
);

alter table public.people enable row level security;

drop policy if exists "Public can view people" on public.people;
drop policy if exists "Anyone can view people" on public.people;
drop policy if exists "Logged in users can add people" on public.people;
drop policy if exists "Logged in users can delete people" on public.people;
drop policy if exists "Signed-in admins can add people" on public.people;
drop policy if exists "Signed-in admins can delete people" on public.people;

create policy "Public can view people"
on public.people for select
to anon, authenticated
using (true);

create policy "Signed-in users can add people"
on public.people for insert
to authenticated
with check (true);

create policy "Signed-in users can delete people"
on public.people for delete
to authenticated
using (true);

grant select on public.people to anon, authenticated;
grant insert, delete on public.people to authenticated;
grant usage, select on sequence public.people_id_seq to authenticated;
