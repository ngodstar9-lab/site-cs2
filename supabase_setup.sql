-- CS2 ARENA database setup
create table if not exists public.people (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) <= 80),
  game_id text,
  role text default 'عضو کامیونیتی',
  created_at timestamptz not null default now()
);

create table if not exists public.news (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) <= 140),
  body text not null check (char_length(body) <= 5000),
  image_url text,
  created_at timestamptz not null default now()
);

alter table public.people enable row level security;
alter table public.news enable row level security;

-- Remove older permissive policies
drop policy if exists "Public can view people" on public.people;
drop policy if exists "Anyone can view people" on public.people;
drop policy if exists "Logged in users can add people" on public.people;
drop policy if exists "Logged in users can delete people" on public.people;
drop policy if exists "Signed-in users can add people" on public.people;
drop policy if exists "Signed-in users can delete people" on public.people;
drop policy if exists "Only manager can add people" on public.people;
drop policy if exists "Only manager can delete people" on public.people;
drop policy if exists "Only manager can update people" on public.people;
drop policy if exists "Public can view news" on public.news;
drop policy if exists "Only manager can add news" on public.news;
drop policy if exists "Only manager can update news" on public.news;
drop policy if exists "Only manager can delete news" on public.news;

create policy "Public can view people" on public.people
for select to anon, authenticated using (true);
create policy "Only manager can add people" on public.people
for insert to authenticated with check (auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid);
create policy "Only manager can update people" on public.people
for update to authenticated using (auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid)
with check (auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid);
create policy "Only manager can delete people" on public.people
for delete to authenticated using (auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid);

create policy "Public can view news" on public.news
for select to anon, authenticated using (true);
create policy "Only manager can add news" on public.news
for insert to authenticated with check (auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid);
create policy "Only manager can update news" on public.news
for update to authenticated using (auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid)
with check (auth.uid() = '8b866c9a-f7c6-4b72-bf5e-8ac5b39887ea'::uuid);
